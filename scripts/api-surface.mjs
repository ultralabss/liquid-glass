#!/usr/bin/env node
// Lists every export of the package entry points (package.json "exports") and writes docs/api-surface.txt.
// Usage: node scripts/api-surface.mjs            → regenerate docs/api-surface.txt
//        node scripts/api-surface.mjs --check    → exit 1 when the current exports differ from the snapshot (npm run check:api)
// JS bundles in dist/ are built from package.json "source" (src/index.ts), so their surface is read from it.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

// <surface>  (dependency-free; read(path) returns file text or null)
export function apiSurface({ pkg, read }) {
  const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
  const parse = (file) => {
    const text = read(file.replace(/^\.\//, ''));
    if (text == null) return { error: 'missing ' + file };
    const src = strip(text), names = new Map();
    for (const m of src.matchAll(/export\s+(type\s+)?\{([^}]*)\}(\s*from\s*['"][^'"]+['"])?/g)) {
      for (let part of m[2].split(',')) {
        part = part.trim(); if (!part) continue;
        let kind = m[1] ? 'type' : 'value';
        if (/^type\s+/.test(part)) { kind = 'type'; part = part.replace(/^type\s+/, ''); }
        const name = part.split(/\s+as\s+/).pop().trim();
        names.set(name, kind);
      }
    }
    for (const m of src.matchAll(/export\s+(?:declare\s+)?(?:default\s+)?(async\s+function|function\*?|const|let|var|class|enum|interface|type)\s+([A-Za-z_$][\w$]*)/g))
      names.set(m[2], /interface|type/.test(m[1]) ? 'type' : 'value');
    if (/export\s+\*/.test(src)) names.set('* (re-export, not listed)', 'value');
    if (/export\s+default\s/.test(src)) names.set('default', 'value');
    return { names };
  };
  const lines = [`# ${pkg.name} ${pkg.version} public API surface. Generated by scripts/api-surface.mjs; do not edit. Check: npm run check:api`];
  const counts = {}, seen = new Map();
  for (const sub of Object.keys(pkg.exports).sort()) {
    const t = pkg.exports[sub];
    const file = typeof t === 'string' ? t : (t.import || t.default);
    const types = typeof t === 'string' ? null : t.types || null;
    let source = null;
    if (/\.tsx?$/.test(file)) source = file;
    else if (/^\.\/dist\/.*\.js$/.test(file)) source = pkg.source;
    lines.push('');
    if (/\.css$/.test(file)) { lines.push(`## ${sub} → ${file} (stylesheet, no exports)`); counts[sub] = 0; continue; }
    if (/\.json$/.test(file) && sub !== './package.json') {
      const j = read(file.replace(/^\.\//, ''));
      const keys = j == null ? [] : Object.keys(JSON.parse(j)).sort();
      lines.push(`## ${sub} → ${file} (json, ${keys.length} top-level keys)`); for (const k of keys) lines.push('key ' + k);
      counts[sub] = keys.length; continue;
    }
    if (sub === './package.json') { lines.push(`## ${sub} (manifest)`); counts[sub] = 0; continue; }
    if (!source) { lines.push(`## ${sub} → ${file} (no parsable source)`); counts[sub] = 0; continue; }
    const head = `## ${sub} → ${file}${types ? ' (types ' + types + ')' : ''} · source ${source}`;
    if (seen.has(source)) { const first = seen.get(source); lines.push(`${head} · same surface as "${first}"${/\.js$/.test(file) && !types ? ' (window.UL)' : ''}`); counts[sub] = counts[first]; continue; }
    const r = parse(source);
    if (r.error) { lines.push(`${head} · ERROR ${r.error}`); counts[sub] = 0; continue; }
    const rows = [...r.names].map(([n, k]) => `${k} ${n}`).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
    const v = rows.filter((x) => x.startsWith('value ')).length;
    lines.push(`${head} · ${rows.length} exports (${v} values, ${rows.length - v} types)`); lines.push(...rows);
    counts[sub] = rows.length; seen.set(source, sub);
  }
  return { text: lines.join('\n') + '\n', counts };
}
export function diffSurface(want, got) {
  const a = new Set(want.split('\n')), b = new Set(got.split('\n')), out = [];
  for (const l of a) if (!b.has(l)) out.push('- ' + l);
  for (const l of b) if (!a.has(l)) out.push('+ ' + l);
  return out;
}
// </surface>

const self = fileURLToPath(import.meta.url);
if (process.argv[1] && resolve(process.argv[1]) === self) {
  const root = resolve(dirname(self), '..');
  const read = (p) => { const f = resolve(root, p); return existsSync(f) ? readFileSync(f, 'utf8') : null; };
  const pkg = JSON.parse(read('package.json'));
  const { text, counts } = apiSurface({ pkg, read });
  const snap = resolve(root, 'docs/api-surface.txt');
  for (const [k, n] of Object.entries(counts)) console.log(`${k}: ${n}`);
  if (process.argv.includes('--check')) {
    const want = existsSync(snap) ? readFileSync(snap, 'utf8') : '';
    const d = diffSurface(want, text);
    if (d.length) { console.log(`API surface differs from docs/api-surface.txt (${d.length} lines). If deliberate: npm run api:snapshot`); for (const l of d) console.log('  ' + l); process.exit(1); }
    console.log('API surface matches docs/api-surface.txt');
  } else { writeFileSync(snap, text); console.log('docs/api-surface.txt written'); }
}
